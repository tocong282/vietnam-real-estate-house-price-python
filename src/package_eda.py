from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile
import nbformat
import pandas as pd

root = Path('/root/vietnam-real-estate-house-price')
out = root / 'deliverables_task1'
fig = out / 'figures'
df = pd.read_parquet(out / 'data_clean_ha_noi.parquet', columns=[
    'district_name','property_type_name','area','bedroom_count',
    'bathroom_count','frontage_width','price','price_per_m2'
])
df['price_trieu'] = df['price'] / 1e6
df['price_m2_trieu'] = df['price_per_m2'] / 1e6

# EDA tables
summary = df.groupby('property_type_name', dropna=False).agg(
    so_tin=('price','count'),
    ty_trong_phan_tram=('price', lambda s: s.count() / len(df) * 100),
    gia_trung_vi_trieu=('price_trieu','median'),
    dien_tich_trung_vi_m2=('area','median'),
    don_gia_trung_vi_trieu=('price_m2_trieu','median'),
).sort_values('so_tin', ascending=False).reset_index()
summary.to_csv(out / 'EDA_E03_summary_by_type.csv', index=False, encoding='utf-8-sig')

ranges = []
for c, label in [('area','Diện tích (m²)'),('price_trieu','Giá (triệu VNĐ)'),('price_m2_trieu','Đơn giá (triệu VNĐ/m²)')]:
    q = df[c].quantile([.01,.50,.99])
    outside = (~df[c].between(q.iloc[0], q.iloc[2])).sum()
    ranges.append({'bien': label, 'P01': q.iloc[0], 'Median': q.iloc[1], 'P99': q.iloc[2], 'so_tin_ngoai_P01_P99': int(outside), 'ty_le_phan_tram': outside/len(df)*100})
pd.DataFrame(ranges).to_csv(out / 'EDA_E01_distribution_ranges.csv', index=False, encoding='utf-8-sig')

num = ['area','bedroom_count','bathroom_count','frontage_width','price_trieu','price_m2_trieu']
corr = df[num].corr(method='spearman')
corr.index = ['area_m2','bedroom_count','bathroom_count','frontage_width_m','price_million_vnd','price_m2_million_vnd']
corr.columns = corr.index
corr.to_csv(out / 'EDA_E06_spearman_correlation.csv', encoding='utf-8-sig')

top = df['district_name'].value_counts().head(12).rename_axis('district_name').reset_index(name='so_tin')
top['ty_trong_phan_tram'] = top['so_tin'] / len(df) * 100
top.to_csv(out / 'EDA_E04_top12_districts.csv', index=False, encoding='utf-8-sig')

# Fix original notebook path + E05 undefined variables, retain source/output cells.
nb_path = out / 'Du_an_BDS_HaNoi_D01_E07_Executed.ipynb'
nb = nbformat.read(nb_path, as_version=4)
for cell in nb.cells:
    if cell.cell_type == 'code' and "df_sub_e05 =" in cell.source and "a_p01" not in cell.source.split("df_sub_e05 =")[0]:
        cell.source = cell.source.replace("p_p01, p_p99 = df_eda['price_trieu'].quantile([0.01, 0.99])", "a_p01, a_p99 = df_eda['area'].quantile([0.01, 0.99])\np_p01, p_p99 = df_eda['price_trieu'].quantile([0.01, 0.99])")
nb.metadata['eda_note'] = 'Figures and CSV tables generated by run_notebook_eda.py on data_clean_ha_noi.parquet (783600 rows).'
nbformat.write(nb, nb_path)

# Package handoff files; omit 407 MB parquet.
zip_path = out / 'task2_eda_files.zip'
include = [
    'Du_an_BDS_HaNoi_D01_E07_Executed.ipynb',
    'EDA_E01_distribution_ranges.csv', 'EDA_E03_summary_by_type.csv',
    'EDA_E04_top12_districts.csv', 'EDA_E06_spearman_correlation.csv',
]
with ZipFile(zip_path, 'w', ZIP_DEFLATED) as z:
    for rel in include:
        z.write(out / rel, rel)
    for p in sorted(fig.glob('*.png')):
        z.write(p, 'figures/' + p.name)
print('rows', len(df))
print(summary.to_string(index=False))
print('zip', zip_path, zip_path.stat().st_size)
